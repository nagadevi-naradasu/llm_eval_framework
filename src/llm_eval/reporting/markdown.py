from typing import Dict, List, Any
import pandas as pd
from pathlib import Path
import os
import json

class MarkdownReportGenerator:
    def __init__(self, output_dir: str):
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    def generate(self, model_name: str, results: pd.DataFrame, summary: Dict[str, float]):
        """
        Generates a Markdown report for a specific model evaluation.
        """
        report_path = Path(self.output_dir) / f"{model_name}_report.md"
        
        with open(report_path, 'w', encoding='utf-8') as f:
            # Title
            f.write(f"# Evaluation Report: {model_name}\n\n")
            
            # Summary Section
            f.write("## 1. Summary Statistics\n\n")
            f.write("| Metric | Score |\n")
            f.write("| :--- | :---: |\n")
            for metric, score in summary.items():
                if isinstance(score, (int, float)):
                    f.write(f"| {metric} | {score:.4f} |\n")
            f.write("\n")
            
            # Visualizations Section
            f.write("## 2. Visualizations\n\n")
            f.write("### Metric Distribution\n")
            # We assume these are generated by the Visualizer
            # This is a bit loose coupling, ideally visualizer and reporter are aware of each other
            # But for now we just link the expected filenames
            numeric_cols = results.select_dtypes(include=['number']).columns
            for col in numeric_cols:
                filename = f"hist_{col.replace('/', '_').replace(' ', '_')}.png"
                f.write(f"![{col}]({filename})\n\n")
                
            f.write("### Radar Chart\n")
            f.write(f"![Radar Chart](radar_{model_name}.png)\n\n")

            # Insights / Detailed Results Section (Top 5 worst/best or just errors)
            f.write("## 3. Detailed Results (Sample)\n\n")
            f.write("First 10 examples:\n\n")
            
            # Convert first 10 rows to markdown table
            head = results.head(10)
            # Truncate long text columns for display
            display_df = head.copy()
            for col in display_df.columns:
                display_df[col] = display_df[col].apply(lambda x: (str(x)[:50] + '...') if isinstance(x, str) and len(str(x)) > 50 else x)
            
            f.write(display_df.to_markdown(index=False))
            f.write("\n\n")
            
        return report_path
